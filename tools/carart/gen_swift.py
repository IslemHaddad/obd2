"""Generate Sources/UI/CarArtPaths.swift from spec.py so the iPhone app draws the exact same artwork."""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import spec  # noqa: E402


def f(v):
    return f"{float(v):.1f}"


MAPS = {
    "side": ("g.sideX(x)", "g.sideY(y)", "1000.0", "g.sideH"),
    "front": ("x", "g.frontY(y)", "600.0", "g.frontH"),
    "top": ("x", "y", "400.0", "900.0"),
}


def path_fn(name, cmds, W, H, view):
    mx, my, w, h = MAPS[view]
    lines = [f"    static func {name}(_ r: CGRect, _ g: CarGeometry = .leon) -> Path {{",
             f"        let sx = r.width / {w}, sy = r.height / {h}",
             f"        func p(_ x: CGFloat, _ y: CGFloat) -> CGPoint {{ CGPoint(x: r.minX + {mx} * sx, y: r.minY + {my} * sy) }}",
             "        var q = Path()"]
    for c in cmds:
        if c[0] == "M":
            lines.append(f"        q.move(to: p({f(c[1])}, {f(c[2])}))")
        elif c[0] == "L":
            lines.append(f"        q.addLine(to: p({f(c[1])}, {f(c[2])}))")
        elif c[0] == "C":
            lines.append(f"        q.addCurve(to: p({f(c[5])}, {f(c[6])}), control1: p({f(c[1])}, {f(c[2])}), "
                         f"control2: p({f(c[3])}, {f(c[4])}))")
        else:
            lines.append("        q.closeSubpath()")
    lines += ["        return q", "    }"]
    return "\n".join(lines)


def main(out):
    parts = ["// GENERATED by tools/carart/gen_swift.py from tools/carart/spec.py — do not edit by hand.",
             "import SwiftUI", "", "enum CarArtPaths {"]
    for prefix, data, W, H in (("side", spec.SIDE, spec.SIDE_W, spec.SIDE_H),
                               ("front", spec.FRONT, spec.FRONT_W, spec.FRONT_H),
                               ("top", spec.TOP, spec.TOP_W, spec.TOP_H)):
        parts.append(f"    static let {prefix}Size = CGSize(width: {W}, height: {H})")
        for k, v in data.items():
            if v and isinstance(v[0], tuple) and isinstance(v[0][0], str):
                name = prefix + "".join(w.capitalize() for w in k.split("_"))
                parts.append(path_fn(name, v, W, H, prefix))
            else:
                arr = ", ".join("[" + ", ".join(f(x) for x in t) + "]" for t in v)
                name = prefix + "".join(w.capitalize() for w in k.split("_"))
                parts.append(f"    static let {name}: [[CGFloat]] = [{arr}]")
    parts.append("}")
    open(out, "w").write("\n\n".join(parts) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
