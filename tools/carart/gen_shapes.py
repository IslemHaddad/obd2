"""Generate Sources/UI/CarShapes.swift from param.py (approved parametric outlines).
Each path is encoded as [[op, ...]]: 0=move x y, 1=line x y, 2=curve c1x c1y c2x c2y x y, 3=close."""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import param  # noqa: E402

# model key → (dimensions, body). Fallbacks for unknown models: by body type.
SHAPES = {
    "leon": param.Car(4263, 1810, 1446, 2636, "hatch"),
    "ibiza": param.Car(4059, 1780, 1444, 2564, "hatch"),
    "arona": param.Car(4138, 1780, 1552, 2566, "suv"),
    "grandi10": param.Car(3765, 1660, 1520, 2425, "hatch"),
    "i10": param.Car(3645, 1660, 1500, 2385, "hatch"),
}


def enc(cmds):
    out = []
    for c in cmds:
        op = {"M": 0, "L": 1, "C": 2, "Z": 3}[c[0]]
        out.append("[" + ", ".join([str(op)] + [f"{v:.1f}" for v in c[1:]]) + "]")
    return "[" + ", ".join(out) + "]"


def main(out):
    s = ["// GENERATED by tools/carart/gen_shapes.py from tools/carart/param.py — do not edit by hand.",
         "import CoreGraphics", "",
         "struct CarSideShape {", "    let size: CGSize, ground: CGFloat, suv: Bool",
         "    let body, glass, cPillar, bPillar, shoulder, crease, headlight, drl, taillight, mirror, sill, handles, cladding: [[CGFloat]]",
         "    let wheels: [[CGFloat]]", "}", "",
         "struct CarFrontShape {", "    let size: CGSize, ground: CGFloat",
         "    let body, glass, headlightL, headlightR, drlL, drlR, intakeL, intakeR, lower, mirrorL, mirrorR: [[CGFloat]]",
         "    let grilles: [String: [[CGFloat]]]", "    let tyres: [[CGFloat]]", "    let badge: CGPoint", "}", "",
         "enum CarShapes {"]
    sides, fronts = [], []
    for key, car in SHAPES.items():
        d = param.side(car)
        sides.append(
            f'        "{key}": CarSideShape(size: CGSize(width: {d["W"]:.1f}, height: {d["H"]:.1f}), ground: {d["ground"]:.1f}, '
            f'suv: {"true" if d["suv"] else "false"},\n'
            f'            body: {enc(d["body"])},\n            glass: {enc(d["glass"])},\n'
            f'            cPillar: {enc(d["c_pillar"])}, bPillar: {enc(d["b_pillar"])},\n'
            f'            shoulder: {enc(d["shoulder"])}, crease: {enc(d["crease"])},\n'
            f'            headlight: {enc(d["headlight"])}, drl: {enc(d["drl"])}, taillight: {enc(d["taillight"])},\n'
            f'            mirror: {enc(d["mirror"])}, sill: {enc(d["sill"])}, handles: {enc(d["handles"])},\n'
            f'            cladding: {enc(d["cladding"])},\n'
            f'            wheels: [' + ", ".join(f"[{a:.1f}, {b:.1f}, {c:.1f}]" for a, b, c in d["wheels"]) + "])")
        fr = {g: param.front(car, grille=g) for g in ("seat", "hyundai", "kia")}
        f = fr["seat"]
        grilles = ", ".join(f'"{g}": {enc(fr[g]["grille"])}' for g in fr)
        fronts.append(
            f'        "{key}": CarFrontShape(size: CGSize(width: {f["W"]:.1f}, height: {f["H"]:.1f}), ground: {f["ground"]:.1f},\n'
            f'            body: {enc(f["body"])},\n            glass: {enc(f["glass"])},\n'
            f'            headlightL: {enc(f["headlight_l"])}, headlightR: {enc(f["headlight_r"])},\n'
            f'            drlL: {enc(f["drl_l"])}, drlR: {enc(f["drl_r"])},\n'
            f'            intakeL: {enc(f["intake_l"])}, intakeR: {enc(f["intake_r"])}, lower: {enc(f["lower"])},\n'
            f'            mirrorL: {enc(f["mirror_l"])}, mirrorR: {enc(f["mirror_r"])},\n'
            f'            grilles: [{grilles}],\n'
            f'            tyres: [' + ", ".join(f"[{a:.1f}, {b:.1f}, {c:.1f}, {e:.1f}]" for a, b, c, e in f["tyres"]) + "],\n"
            f'            badge: CGPoint(x: {f["badge"][0]:.1f}, y: {f["badge"][1]:.1f}))')
    s.append("    static let side: [String: CarSideShape] = [\n" + ",\n".join(sides) + "\n    ]")
    s.append("    static let front: [String: CarFrontShape] = [\n" + ",\n".join(fronts) + "\n    ]")
    s.append("}")
    open(out, "w").write("\n".join(s) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
