/// Per-car drawing parameters derived from brand + model (drawn, not photos).
struct CarArt {
    let color: Color
    let body: BodyType
    let brand: String
    let model: String
    let roofHeight: CGFloat      // 0…1 relative to car height in side/front views
    let twoTone: Bool            // contrasting roof (e.g. Arona / Venue)
    let grille: Grille
    let geo: CarGeometry
    let shapeKey: String
    enum Grille { case seat, hyundai, kia, renault, vw, generic }

    init(_ v: SelectedVehicle) {
        color = v.brand.color
        body = v.model.body
        brand = v.brand.rawValue.uppercased()
        model = v.model.name
        let n = v.model.name.lowercased()
        geo = CarGeometry.forModel(v.model.name, body: v.model.body)
        if n.contains("grand i10") { shapeKey = "grandi10" }
        else if n.contains("i10") { shapeKey = "i10" }
        else if n.contains("arona") { shapeKey = "arona" }
        else if n.contains("ibiza") { shapeKey = "ibiza" }
        else if n.contains("leon") || n.contains("león") { shapeKey = "leon" }
        else if n.contains("clio iv") { shapeKey = "clio4" }
        else if n.contains("clio") { shapeKey = "clio5" }
        else if n.contains("captur") { shapeKey = "captur" }
        else if n.contains("mégane") || n.contains("megane") { shapeKey = "megane" }
        else if n.contains("symbol") || v.model.body == .sedan { shapeKey = "symbol" }
        else {
            switch v.model.body {
            case .suv, .van: shapeKey = "arona"
            case .hatch: shapeKey = "ibiza"
            default: shapeKey = "leon"
            }
        }
        twoTone = ["arona", "venue", "kona", "t-cross", "kamiq", "sonet"].contains { n.contains($0) }
        switch v.model.body {
        case .suv: roofHeight = 0.62
        case .van: roofHeight = 0.70
        case .coupe: roofHeight = 0.48
        case .sedan, .estate: roofHeight = 0.52
        case .hatch: roofHeight = n.contains("i10") || n.contains("picanto") || n.contains("up") ? 0.60 : 0.55
        }
        switch v.brand {
        case .seat, .cupra: grille = .seat
        case .hyundai: grille = .hyundai
        case .kia: grille = .kia
        case .renault: grille = .renault
        case .vw, .skoda, .audi: grille = .vw
        default: grille = .generic
        }
    }
}

// MARK: - Side & front views (parametric outlines from real dimensions; data in CarShapes.swift, generated by tools/carart)

func carPath(_ d: [[CGFloat]], _ t: (CGFloat, CGFloat) -> CGPoint) -> Path {
    var p = Path()
    for c in d {
        switch Int(c[0]) {
        case 0: p.move(to: t(c[1], c[2]))
        case 1: p.addLine(to: t(c[1], c[2]))
        case 2: p.addCurve(to: t(c[5], c[6]), control1: t(c[1], c[2]), control2: t(c[3], c[4]))
        default: p.closeSubpath()
        }
    }
    return p
}

struct CarSideView: View {
    let art: CarArt
    var body: some View {
        Canvas { ctx, size in
            guard let d = CarShapes.side[art.shapeKey] else { return }
            let k = min(size.width / d.size.width, size.height / d.size.height)
            let ox = (size.width - d.size.width * k) / 2, oy = (size.height - d.size.height * k) / 2
            let t: (CGFloat, CGFloat) -> CGPoint = { x, y in CGPoint(x: ox + x * k, y: oy + y * k) }
            let P = { (cmds: [[CGFloat]]) in carPath(cmds, t) }
            let gy = oy + d.ground * k
            ctx.fill(Path(ellipseIn: CGRect(x: ox + d.size.width * k * 0.04, y: gy - 5, width: d.size.width * k * 0.92, height: 10)),
                     with: .color(.black.opacity(0.5)))
            let c = art.color
            ctx.fill(P(d.body), with: .linearGradient(
                Gradient(stops: [.init(color: c.opacity(0.75), location: 0), .init(color: c, location: 0.35),
                                 .init(color: c.opacity(0.85), location: 0.36), .init(color: c.opacity(0.55), location: 1)]),
                startPoint: CGPoint(x: 0, y: oy), endPoint: CGPoint(x: 0, y: gy)))
            ctx.stroke(P(d.body), with: .color(.white.opacity(0.2)), lineWidth: 1)
            if !d.cladding.isEmpty { ctx.fill(P(d.cladding), with: .color(Color(white: 0.12))) }
            ctx.fill(P(d.glass), with: .linearGradient(Gradient(colors: [Color(white: 0.38), Color(white: 0.06)]),
                                                       startPoint: CGPoint(x: 0, y: oy), endPoint: CGPoint(x: 0, y: oy + d.size.height * k * 0.35)))
            ctx.fill(P(d.cPillar), with: .color(Color(white: 0.03)))
            ctx.fill(P(d.bPillar), with: .color(Color(white: 0.03)))
            ctx.fill(P(d.mirror), with: .color(c.opacity(0.85)))
            ctx.fill(P(d.headlight), with: .color(Color(white: 0.12)))
            ctx.fill(P(d.taillight), with: .color(.red))
            ctx.stroke(P(d.shoulder), with: .color(.white.opacity(0.3)), lineWidth: 1.2)
            ctx.stroke(P(d.crease), with: .color(.black.opacity(0.28)), lineWidth: 1.2)
            ctx.stroke(P(d.sill), with: .color(.black.opacity(0.45)), lineWidth: 1.6)
            ctx.stroke(P(d.drl), with: .color(Color(red: 0.75, green: 0.96, blue: 1)), style: StrokeStyle(lineWidth: 2, lineCap: .round))
            ctx.stroke(P(d.handles), with: .color(.black.opacity(0.45)), style: StrokeStyle(lineWidth: 2, lineCap: .round))
            for w in d.wheels {
                let ctr = t(w[0], w[1]), r = w[2] * k
                ctx.fill(Path(ellipseIn: CGRect(x: ctr.x - r, y: ctr.y - r, width: 2 * r, height: 2 * r)), with: .color(Color(white: 0.06)))
                ctx.fill(Path(ellipseIn: CGRect(x: ctr.x - r * 0.7, y: ctr.y - r * 0.7, width: 1.4 * r, height: 1.4 * r)),
                         with: .radialGradient(Gradient(colors: [Color(white: 0.85), Color(white: 0.55)]), center: ctr,
                                               startRadius: 0, endRadius: r * 0.7))
                for i in 0..<5 {                                         // 5 spoke windows
                    let a = Double(i) * 2 * .pi / 5
                    var q = Path()
                    q.move(to: CGPoint(x: ctr.x + cos(a + 0.22) * r * 0.2, y: ctr.y + sin(a + 0.22) * r * 0.2))
                    q.addLine(to: CGPoint(x: ctr.x + cos(a + 0.30) * r * 0.62, y: ctr.y + sin(a + 0.30) * r * 0.62))
                    q.addLine(to: CGPoint(x: ctr.x + cos(a + 0.98) * r * 0.62, y: ctr.y + sin(a + 0.98) * r * 0.62))
                    q.addLine(to: CGPoint(x: ctr.x + cos(a + 1.06) * r * 0.2, y: ctr.y + sin(a + 1.06) * r * 0.2))
                    q.closeSubpath()
                    ctx.fill(q, with: .color(Color(white: 0.12)))
                }
                ctx.fill(Path(ellipseIn: CGRect(x: ctr.x - r * 0.14, y: ctr.y - r * 0.14, width: r * 0.28, height: r * 0.28)),
                         with: .color(Color(white: 0.3)))
            }
        }
    }
}

struct CarFrontView: View {
    let art: CarArt
    var body: some View {
        Canvas { ctx, size in
            guard let d = CarShapes.front[art.shapeKey] else { return }
            let k = min(size.width / d.size.width, size.height / d.size.height)
            let ox = (size.width - d.size.width * k) / 2, oy = (size.height - d.size.height * k) / 2
            let t: (CGFloat, CGFloat) -> CGPoint = { x, y in CGPoint(x: ox + x * k, y: oy + y * k) }
            let P = { (cmds: [[CGFloat]]) in carPath(cmds, t) }
            let gy = oy + d.ground * k
            ctx.fill(Path(ellipseIn: CGRect(x: ox + d.size.width * k * 0.05, y: gy - 4, width: d.size.width * k * 0.9, height: 8)),
                     with: .color(.black.opacity(0.5)))
            for ty in d.tyres {
                ctx.fill(Path(roundedRect: CGRect(x: ox + ty[0] * k, y: oy + ty[1] * k, width: ty[2] * k, height: ty[3] * k), cornerRadius: 4),
                         with: .color(Color(white: 0.05)))
            }
            let c = art.color
            ctx.fill(P(d.body), with: .linearGradient(Gradient(colors: [c.opacity(0.55), c, c.opacity(0.95), c, c.opacity(0.55)]),
                                                      startPoint: CGPoint(x: ox, y: 0), endPoint: CGPoint(x: ox + d.size.width * k, y: 0)))
            ctx.stroke(P(d.body), with: .color(.white.opacity(0.2)), lineWidth: 1)
            ctx.fill(P(d.glass), with: .linearGradient(Gradient(colors: [Color(white: 0.4), Color(white: 0.06)]),
                                                       startPoint: CGPoint(x: 0, y: oy), endPoint: CGPoint(x: 0, y: oy + d.size.height * k * 0.45)))
            ctx.fill(P(d.mirrorL), with: .color(c.opacity(0.85)))
            ctx.fill(P(d.mirrorR), with: .color(c.opacity(0.85)))
            ctx.fill(P(d.headlightL), with: .color(Color(white: 0.11)))
            ctx.fill(P(d.headlightR), with: .color(Color(white: 0.11)))
            let led = Color(red: 0.78, green: 0.96, blue: 1)
            ctx.stroke(P(d.drlL), with: .color(led), style: StrokeStyle(lineWidth: 2.4, lineCap: .round, lineJoin: .round))
            ctx.stroke(P(d.drlR), with: .color(led), style: StrokeStyle(lineWidth: 2.4, lineCap: .round, lineJoin: .round))
            let gkey: String = { switch art.grille { case .hyundai: "hyundai"; case .kia: "kia"; case .renault: "renault"; default: "seat" } }()
            if let g = d.grilles[gkey] {
                ctx.fill(P(g), with: .color(Color(white: 0.06)))
                ctx.stroke(P(g), with: .color(Color(white: 0.78)), lineWidth: 1.6)
            }
            ctx.fill(P(d.intakeL), with: .color(Color(white: 0.06)))
            ctx.fill(P(d.intakeR), with: .color(Color(white: 0.06)))
            ctx.fill(P(d.lower), with: .color(Color(white: 0.06)))
            if art.grille != .renault {                 // Renault: the diamond in the grille is the badge
                ctx.draw(Text(art.brand).font(.system(size: max(7, 9 * k * 1.6), weight: .heavy, design: .rounded)).foregroundColor(.white),
                         at: t(d.badge.x, d.badge.y))
            }
        }
    }
}

// MARK: - Showcase shown while scanning: 3 visuals rotating with a scan sweep

struct ScanShowcase: View {
    let vehicle: SelectedVehicle
    let progress: Double
    let status: String
    @State private var page = 0
    @State private var sweep = false
    private let timer = Timer.publish(every: 2.6, on: .main, in: .common).autoconnect()

    var body: some View {
        let art = CarArt(vehicle)
        VStack(spacing: 12) {
            TabView(selection: $page) {
                CarSideView(art: art).padding(20).tag(0)
                CarFrontView(art: art).padding(20).tag(1)
                CarTopView(color: art.color, body: art.body)
                    .frame(width: 150, height: 150 * art.geo.topAspect).rotationEffect(.degrees(90))
                    .frame(maxWidth: .infinity, maxHeight: .infinity).tag(2)
            }
            .tabViewStyle(.page(indexDisplayMode: .always))
            .frame(height: 230)
            .overlay {
                GeometryReader { g in
                    LinearGradient(colors: [.clear, art.color.opacity(0.55), .white.opacity(0.7), art.color.opacity(0.55), .clear],
                                   startPoint: .leading, endPoint: .trailing)
                        .frame(width: 70)
                        .blur(radius: 6)
                        .offset(x: sweep ? g.size.width : -70)
                        .blendMode(.screen)
                        .allowsHitTesting(false)
                }
                .clipped()
            }
            .background(RadialGradient(colors: [art.color.opacity(0.25), .clear], center: .center, startRadius: 10, endRadius: 220))
            VStack(spacing: 6) {
                Text("\(art.brand) \(art.model)").font(.headline)
                ProgressView(value: progress).tint(art.color)
                Text(status).font(.caption).foregroundStyle(.secondary).lineLimit(1)
            }
            .padding(.horizontal, 24)
        }
        .onAppear { withAnimation(.linear(duration: 1.6).repeatForever(autoreverses: false)) { sweep = true } }
        .onReceive(timer) { _ in withAnimation(.easeInOut(duration: 0.6)) { page = (page + 1) % 3 } }
    }
}

/// Static 3-view gallery (side / front / top) for the vehicle header.
struct CarGallery: View {
    let vehicle: SelectedVehicle
    var body: some View {
        let art = CarArt(vehicle)
        TabView {
            CarSideView(art: art).padding(16)
            CarFrontView(art: art).padding(16)
            CarTopView(color: art.color, body: art.body)
                .frame(width: 120, height: 120 * art.geo.topAspect).rotationEffect(.degrees(90))
                .frame(maxWidth: .infinity, maxHeight: .infinity)
        }
        .tabViewStyle(.page(indexDisplayMode: .always))
        .frame(height: 190)
    }
}
